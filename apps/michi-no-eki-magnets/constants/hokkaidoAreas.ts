export function isHokkaidoAreaId(value: string): value is HokkaidoAreaId {
  return (HOKKAIDO_AREA_IDS as readonly string[]).includes(value);
}

export function getHokkaidoArea(city: string): HokkaidoAreaId | null {
  return cityToArea.get(city) ?? null;
}

/** Prefecture filter key used in location filters (sub-area for Hokkaido stations). */
export function getStationLocationFilterKey(station: {
  prefecture: string;
  city: string;
}): string {
  if (station.prefecture === HOKKAIDO_PREFECTURE) {
    return getHokkaidoArea(station.city) ?? HOKKAIDO_PREFECTURE;
  }

  return station.prefecture;
}
